#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Retro Recoil - map generator.

Writes retro_recoil_map.obj, the Wavefront OBJ model the game server loads.
The server only ever reads the .obj - this script is just a convenient way to
(re)generate or tweak it.  You can also edit the .obj by hand / in Blender as
long as you keep the conventions listed in imp-meta.md ("map-format").

Layout (units are metres, +x east, +z north, y is up):

    Courtyard A  (spawn yard)   x 0..32,  z 0..32
    Courtyard B  (next door)    x 36.6..68.6, z 0..32
    Each yard is ringed by a building: inner wall, hallway, outer wall.
      * 8 hallway doorways per yard   (16 in the whole map)
      * 4 crouch holes per yard       (8 in the whole map), each leading to an
        isolated hide box: in through the hole, then a turn to the right
      * the east side of A and the west side of B share ONE "main hallway";
        walking through it is how you get from yard A to yard B
      * a low crouch-level vent in each wall of the main hallway is the only
        way to see the other yard from where you stand
"""
import math
import sys

H = 3.0            # wall height
WT = 0.5           # wall thickness
HALL_W = 3.6       # hallway width
BUILD_T = WT + HALL_W + WT      # 4.6, thickness of a building ring
YARD = 32.0        # yard edge length
DOOR_W, DOOR_H = 2.2, 2.4
HOLE_W, HOLE_H = 1.4, 1.0
VENT_W, VENT_LO, VENT_HI = 1.6, 0.35, 1.05
COVER = True       # a few low crates in each yard (set False for an empty yard)
COVER_H = 1.1

YARD_A = (0.0, 0.0)
YARD_B = (YARD + BUILD_T, 0.0)           # 36.6, 0


class Obj:
    def __init__(self):
        self.v, self.vn, self.lines = [], [], []
        self.vi, self.ni = {}, {}

    def vert(self, x, y, z):
        k = (round(x, 4), round(y, 4), round(z, 4))
        i = self.vi.get(k)
        if i is None:
            self.v.append(k)
            i = self.vi[k] = len(self.v)
        return i

    def norm(self, x, y, z):
        k = (round(x, 4), round(y, 4), round(z, 4))
        i = self.ni.get(k)
        if i is None:
            self.vn.append(k)
            i = self.ni[k] = len(self.vn)
        return i

    def group(self, name):
        self.lines.append("g " + name)

    def mtl(self, name):
        self.lines.append("usemtl " + name)

    def vquad(self, p0, p1, y0, y1, n):
        a = self.vert(p0[0], y0, p0[1])
        b = self.vert(p1[0], y0, p1[1])
        c = self.vert(p1[0], y1, p1[1])
        d = self.vert(p0[0], y1, p0[1])
        k = self.norm(n[0], 0.0, n[1])
        self.lines.append(f"f {a}//{k} {b}//{k} {c}//{k} {d}//{k}")

    def hquad(self, x0, z0, x1, z1, y):
        a = self.vert(x0, y, z0)
        b = self.vert(x1, y, z0)
        c = self.vert(x1, y, z1)
        d = self.vert(x0, y, z1)
        k = self.norm(0, 1, 0)
        self.lines.append(f"f {a}//{k} {b}//{k} {c}//{k} {d}//{k}")

    def point(self, x, y, z):
        self.lines.append(f"p {self.vert(x, y, z)}")

    def write(self, path):
        with open(path, "w", newline="\n") as f:
            f.write("# Retro Recoil map - generated by make_map.py\n")
            f.write("# vertical faces = walls (vn gives the outward normal), group/usemtl select behaviour\n")
            for x, y, z in self.v:
                f.write(f"v {x:.4f} {y:.4f} {z:.4f}\n")
            for x, y, z in self.vn:
                f.write(f"vn {x:.4f} {y:.4f} {z:.4f}\n")
            f.write("\n".join(self.lines) + "\n")


class Frame:
    """Local (u along the wall, v outward from the yard) -> world (x, z)."""

    def __init__(self, origin, U, V):
        self.O, self.U, self.V = origin, U, V
        right = (V[1], -V[0])                     # direction of a right turn when walking along +V
        self.s = int(round(right[0] * U[0] + right[1] * U[1]))   # +1 if "right" == +U

    def pt(self, u, v):
        return (self.O[0] + self.U[0] * u + self.V[0] * v, self.O[1] + self.U[1] * u + self.V[1] * v)

    def vec(self, du, dv):
        return (self.U[0] * du + self.V[0] * dv, self.U[1] * du + self.V[1] * dv)

    def rect(self, u0, u1, v0, v1):
        a, b = self.pt(u0, v0), self.pt(u1, v1)
        return (min(a[0], b[0]), min(a[1], b[1]), max(a[0], b[0]), max(a[1], b[1]))

    def face(self, o, u0, v0, u1, v1, y0, y1, nu, nv):
        o.vquad(self.pt(u0, v0), self.pt(u1, v1), y0, y1, self.vec(nu, nv))

    def box(self, o, u0, u1, v0, v1, y0, y1, sides=("u+", "u-", "v+", "v-")):
        if "u+" in sides:
            self.face(o, u1, v0, u1, v1, y0, y1, 1, 0)
        if "u-" in sides:
            self.face(o, u0, v0, u0, v1, y0, y1, -1, 0)
        if "v+" in sides:
            self.face(o, u0, v1, u1, v1, y0, y1, 0, 1)
        if "v-" in sides:
            self.face(o, u0, v0, u1, v0, y0, y1, 0, -1)


def wall_run(o, fr, u0, u1, v0, v1, openings, mat_solid="wall"):
    """A wall along u0..u1 with openings [(centre, width, lo, hi, lintel_mat)]."""
    cur = u0
    for c, w, lo, hi in sorted(openings):
        a, b = c - w / 2.0, c + w / 2.0
        if a > cur + 1e-6:
            o.mtl(mat_solid)
            fr.box(o, cur, a, v0, v1, 0.0, H)
        o.mtl("lintel")
        fr.box(o, a, b, v0, v1, hi, H, sides=("v+", "v-"))
        if lo > 0:
            o.mtl("sill")
            fr.box(o, a, b, v0, v1, 0.0, lo, sides=("v+", "v-"))
        cur = b
    if u1 > cur + 1e-6:
        o.mtl(mat_solid)
        fr.box(o, cur, u1, v0, v1, 0.0, H)


def hide_box(o, fr, hz0, hz1, rects):
    """Crouch hole + tunnel + right-hand pocket.  Returns (hole opening, hide-point)."""
    s = fr.s
    a_, b_ = None, None
    if s > 0:
        hc = hz0 + 1.5
    else:
        hc = hz1 - 1.5
    a, b = hc - HOLE_W / 2, hc + HOLE_W / 2
    v0, vE, vp = WT, 3.3, 1.7
    c = b + 2.6 if s > 0 else a - 2.6
    o.mtl("hide")
    if s > 0:
        fr.face(o, a, v0, a, vE, 0, H, 1, 0)       # left wall of tunnel + pocket
        fr.face(o, a, vE, c, vE, 0, H, 0, -1)      # far wall
        fr.face(o, c, vp, c, vE, 0, H, -1, 0)      # pocket end
        fr.face(o, b, vp, c, vp, 0, H, 0, 1)       # step between tunnel and pocket
        fr.face(o, b, v0, b, vp, 0, H, -1, 0)      # right wall of tunnel (up to pocket)
        pocket = (b, c)
    else:
        fr.face(o, b, v0, b, vE, 0, H, -1, 0)
        fr.face(o, c, vE, b, vE, 0, H, 0, -1)
        fr.face(o, c, vp, c, vE, 0, H, 1, 0)
        fr.face(o, c, vp, a, vp, 0, H, 0, 1)
        fr.face(o, a, v0, a, vp, 0, H, 1, 0)
        pocket = (c, a)
    # low (crouch height) ceiling over hole thickness, tunnel and pocket
    rects.append(fr.rect(a, b, 0.0, vE))
    rects.append(fr.rect(min(pocket), max(pocket), vp, vE))
    pu = (pocket[0] + pocket[1]) / 2.0
    return (hc, HOLE_W, 0.0, HOLE_H), fr.pt(pu, (vp + vE) / 2.0)


def pillars_yard(o, fr, u_list, depth=0.35, w=0.7):
    o.mtl("pillar")
    for u in u_list:
        fr.box(o, u - w / 2, u + w / 2, -depth, 0.0, 0.0, H, sides=("u+", "u-", "v-"))


def pillars_hall(o, fr, u_list, v_wall, depth=0.35, w=0.7):
    o.mtl("pillar")
    for u in u_list:
        fr.box(o, u - w / 2, u + w / 2, v_wall - depth, v_wall, 0.0, H, sides=("u+", "u-", "v-"))


def free_pillar_positions(lo, hi, openings, step=4.0, clear=1.9):
    out = []
    u = lo + 2.0
    while u < hi - 1.0:
        if all(abs(u - c) >= clear + w / 2 - 1.0 for c, w, *_ in openings):
            out.append(u)
        u += step
    return out


def build_ring_side(o, fr, hide_end, roofs, lowceils, hides, door_set=None, shared_far=False):
    """Standard (non shared) ring side of a yard."""
    hz = (0.0, 6.0) if hide_end == "start" else (YARD - 6.0, YARD)
    ha = (6.0, YARD) if hide_end == "start" else (0.0, YARD - 6.0)
    span = ha[1] - ha[0]
    doors = [(ha[0] + span * 0.27, DOOR_W, 0.0, DOOR_H), (ha[0] + span * 0.73, DOOR_W, 0.0, DOOR_H)]
    hole, hidepoint = hide_box(o, fr, hz[0], hz[1], lowceils)
    hides.append(hidepoint)
    openings = doors + [hole]
    wall_run(o, fr, 0.0, YARD, 0.0, WT, openings)
    # outer wall (hallway face only)
    o.mtl("wall")
    fr.box(o, ha[0], ha[1], WT + HALL_W, BUILD_T, 0.0, H, sides=("v-",))
    # hallway end walls
    if hide_end == "start":
        fr.box(o, ha[0] - WT, ha[0], WT, WT + HALL_W, 0.0, H, sides=("u+",))
        fr.box(o, ha[1], ha[1] + WT, WT, WT + HALL_W, 0.0, H, sides=("u-",))
    else:
        fr.box(o, ha[0] - WT, ha[0], WT, WT + HALL_W, 0.0, H, sides=("u+",))
        fr.box(o, ha[1], ha[1] + WT, WT, WT + HALL_W, 0.0, H, sides=("u-",))
    pillars_yard(o, fr, free_pillar_positions(0.0, YARD, openings))
    pillars_hall(o, fr, [ha[0] + 4.2 + 4.8 * i for i in range(4) if ha[0] + 4.2 + 4.8 * i < ha[1] - 2],
                 WT + HALL_W)
    roofs.append(fr.rect(0.0, YARD, 0.0, BUILD_T))


def build_main_hallway(o, frA, frB, roofs, lowceils, hides):
    """Shared building: A-side wall (frame frA), hallway, B-side wall (frame frB)."""
    ha = (6.0, YARD - 6.0)              # hallway runs u 6..26
    span = ha[1] - ha[0]
    vent = (YARD / 2.0, VENT_W, VENT_LO, VENT_HI)
    doorsA = [(ha[0] + span * 0.15, DOOR_W, 0.0, DOOR_H), (ha[0] + span * 0.85, DOOR_W, 0.0, DOOR_H)]
    # A side: hide zone at u 0..6 (south end)
    holeA, hpA = hide_box(o, frA, 0.0, 6.0, lowceils)
    hides.append(hpA)
    openA = doorsA + [vent, holeA]
    wall_run(o, frA, 0.0, YARD, 0.0, WT, openA)
    # B side: hide zone at u 26..32 (north end)
    holeB, hpB = hide_box(o, frB, YARD - 6.0, YARD, lowceils)
    hides.append(hpB)
    openB = doorsA + [vent, holeB]
    wall_run(o, frB, 0.0, YARD, 0.0, WT, openB)
    # hallway end walls (inside the shared hallway, frame A)
    o.mtl("wall")
    frA.box(o, ha[0] - WT, ha[0], WT, WT + HALL_W, 0.0, H, sides=("u+",))
    frA.box(o, ha[1], ha[1] + WT, WT, WT + HALL_W, 0.0, H, sides=("u-",))
    pillars_yard(o, frA, free_pillar_positions(0.0, YARD, openA))
    pillars_yard(o, frB, free_pillar_positions(0.0, YARD, openB))
    # a few pillars inside the hallway
    o.mtl("pillar")
    for u in (11.0, 21.0):
        frA.box(o, u - 0.35, u + 0.35, WT + 1.2, WT + 1.9, 0.0, H, sides=("u+", "u-", "v+", "v-"))
    roofs.append(frA.rect(0.0, YARD, 0.0, BUILD_T))


def cover_blocks(o, ox, oz):
    o.mtl("cover")
    for cx, cz in ((10.5, 10.5), (21.5, 10.5), (10.5, 21.5), (21.5, 21.5)):
        x0, z0 = ox + cx - 0.7, oz + cz - 0.7
        x1, z1 = ox + cx + 0.7, oz + cz + 0.7
        o.vquad((x0, z1), (x1, z1), 0.0, COVER_H, (0, 1))
        o.vquad((x0, z0), (x1, z0), 0.0, COVER_H, (0, -1))
        o.vquad((x1, z0), (x1, z1), 0.0, COVER_H, (1, 0))
        o.vquad((x0, z0), (x0, z1), 0.0, COVER_H, (-1, 0))


def main(path="retro_recoil_map.obj"):
    o = Obj()
    roofs, lowceils, hides = [], [], []
    ax, az = YARD_A
    bx, bz = YARD_B

    def frames(x0, z0):
        return {
            "S": Frame((x0, z0), (1, 0), (0, -1)),
            "N": Frame((x0, z0 + YARD), (1, 0), (0, 1)),
            "W": Frame((x0, z0), (0, 1), (-1, 0)),
            "E": Frame((x0 + YARD, z0), (0, 1), (1, 0)),
        }

    fa, fb = frames(ax, az), frames(bx, bz)
    o.group("walls")
    # pinwheel hide boxes: S near SW, W near NW, N near NE, E near SE
    build_ring_side(o, fa["S"], "start", roofs, lowceils, hides)
    build_ring_side(o, fa["W"], "end", roofs, lowceils, hides)
    build_ring_side(o, fa["N"], "end", roofs, lowceils, hides)
    build_ring_side(o, fb["S"], "start", roofs, lowceils, hides)
    build_ring_side(o, fb["N"], "end", roofs, lowceils, hides)
    build_ring_side(o, fb["E"], "start", roofs, lowceils, hides)
    build_main_hallway(o, fa["E"], fb["W"], roofs, lowceils, hides)
    if COVER:
        o.group("cover")
        cover_blocks(o, ax, az)
        cover_blocks(o, bx, bz)
    # horizontal faces
    o.group("roof")
    for r in roofs:
        o.hquad(r[0], r[1], r[2], r[3], H)
    o.group("lowceil")
    for r in lowceils:
        o.hquad(r[0], r[1], r[2], r[3], 1.0)
    o.group("yardA")
    o.hquad(ax, az, ax + YARD, az + YARD, 0.0)
    o.group("yardB")
    o.hquad(bx, bz, bx + YARD, bz + YARD, 0.0)
    # spawn points (point elements)
    pts = [(6, 6), (16, 5), (26, 6), (5, 16), (16, 16), (27, 16), (6, 26), (16, 27), (26, 26)]
    o.group("spawnA")
    for px, pz in pts:
        o.point(ax + px, 0.0, az + pz)
    o.group("spawnB")
    for px, pz in pts:
        o.point(bx + px, 0.0, bz + pz)
    o.group("hide")
    for hx, hz in hides:
        o.point(hx, 0.0, hz)
    o.write(path)
    print(f"wrote {path}: {len(o.v)} vertices, {sum(1 for l in o.lines if l.startswith('f '))} faces")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "retro_recoil_map.obj")
